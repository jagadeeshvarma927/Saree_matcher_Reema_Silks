
import json
from pathlib import Path

import numpy as np


PROJECT_ROOT = Path(__file__).resolve().parents[2]

DATA_DIR = PROJECT_ROOT / "app" / "data"

CATALOG_PATH = DATA_DIR / "sarees.json"
EMBEDDINGS_PATH = DATA_DIR / "saree_embeddings.npy"
IDS_PATH = DATA_DIR / "saree_embedding_ids.json"


class SimilarityService:
    """Find sarees that are visually similar to a query image."""

    def __init__(self):
        self.embeddings = np.load(EMBEDDINGS_PATH).astype(
            np.float32
        )

        with CATALOG_PATH.open("r", encoding="utf-8") as file:
            catalog = json.load(file)

        with IDS_PATH.open("r", encoding="utf-8") as file:
            self.saree_ids = json.load(file)

        if self.embeddings.ndim != 2:
            raise ValueError("Embeddings must be a 2D array.")

        if self.embeddings.shape[0] != len(self.saree_ids):
            raise ValueError(
                "Embedding count and saree ID count do not match."
            )

        if not np.isfinite(self.embeddings).all():
            raise ValueError("Embeddings contain invalid values.")

        # Store catalog records by ID for quick lookup.
        self.catalog_by_id = {
            item["saree_id"]: item
            for item in catalog
            if item.get("saree_id")
        }

        missing_ids = [
            saree_id
            for saree_id in self.saree_ids
            if saree_id not in self.catalog_by_id
        ]

        if missing_ids:
            raise ValueError(
                f"Some embedding IDs are missing from catalog: "
                f"{missing_ids}"
            )

        # Normalize the catalog vectors defensively.
        norms = np.linalg.norm(
            self.embeddings,
            axis=1,
            keepdims=True
        )

        self.embeddings = self.embeddings / np.maximum(
            norms, 1e-12
        )

        print(
            f"Similarity service loaded "
            f"{len(self.saree_ids)} sarees."
        )

    def search(self, query_embedding, top_k=5):
        """
        Return the top_k visually similar sarees.

        query_embedding:
            A 512-dimensional vector generated by the same
            OpenCLIP model used for the saree catalog.
        """

        query = np.asarray(
            query_embedding,
            dtype=np.float32
        ).reshape(-1)

        if query.shape[0] != self.embeddings.shape[1]:
            raise ValueError(
                f"Expected a {self.embeddings.shape[1]}-dimensional "
                f"query vector, got {query.shape[0]} dimensions."
            )

        if not np.isfinite(query).all():
            raise ValueError("Query embedding contains invalid values.")

        query_norm = np.linalg.norm(query)

        if query_norm < 1e-12:
            raise ValueError("Query embedding has zero magnitude.")

        query = query / query_norm

        if top_k < 1:
            raise ValueError("top_k must be at least 1.")

        # Both sides are normalized, so dot product = cosine similarity.
        scores = self.embeddings @ query

        # Rank from highest to lowest similarity.
        top_indices = np.argsort(scores)[::-1][
            :min(top_k, len(scores))
        ]

        results = []

        for index in top_indices:
            saree_id = self.saree_ids[int(index)]
            product = self.catalog_by_id[saree_id]

            results.append({
                "saree_id": saree_id,
                "name": product.get("name"),
                "price": product.get("price"),
                "image": product.get("image"),
                "image_path": str(
                    PROJECT_ROOT
                    / "processed_images"
                    / f"{saree_id}.jpg"
                ),
                "product_url": product.get("product_url"),
                "similarity": round(
                    float(scores[index]), 4
                )
            })

        return results
